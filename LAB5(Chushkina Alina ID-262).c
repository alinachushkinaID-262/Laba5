// Домашнее задание (Вариант 5): Вычисление величины alpha
// -------------------------------------------------------------
void home_task_var5(void)
{
    printf("\n--- ДОМАШНЕЕ ЗАДАНИЕ (ВАРИАНТ 5) ---\n");

    // Исходные данные для Варианта 5 с последнего фото:
    double x = -15.246;
    double y = 4.642e-2;  // 4.642 * 10^-2
    double z = 20.001e2;  // 20.001 * 10^2

    printf("Исходные данные Варианта 5:\n");
    printf("x = %.3f\n", x);
    printf("y = %e (0.04642)\n", y);
    printf("z = %e (2000.1)\n\n", z);

    // Формула 5: alpha = ln(y^(-sqrt(|x|))) * (x - y/2) + sin^2(atan(z))
    double term1 = log(pow(y, -sqrt(fabs(x))));
    double term2 = (x - y / 2.0);
    double term3 = pow(sin(atan(z)), 2);

    double alpha = term1 * term2 + term3;

    printf("Результат вычисления alpha = %.6f (Контрольное значение: 182.036)\n", fabs(alpha));
}