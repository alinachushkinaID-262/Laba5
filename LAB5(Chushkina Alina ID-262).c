// Задание 2 и 3* (Вариант 5):
// Вычисление функций a, b, y и проверка логических условий
// -------------------------------------------------------------
void task2_and_3star(void)
{
    printf("\n--- ЗАДАНИЕ 2 и 3* (ВАРИАНТ 5) ---\n");
    const double p = 3.0; // Константа из Варианта 5
    double x;

    printf("Введите значение x (контрольное значение 4.1): ");
    scanf("%lf", &x);

    // Вычисления по формулам Варианта 5:
    // a = sqrt(p * x)
    // b = p * x^2 + sqrt(a)
    // y = ln^3(b^2) + a * x
    double a = sqrt(p * x);
    double b = p * pow(x, 2) + sqrt(a);
    double y = pow(log(pow(b, 2)), 3) + a * x;

    printf("\n--- Результаты расчетов ---\n");
    printf("x = %.2f\n", x);
    printf("a = %.6f\n", a);
    printf("b = %.6f\n", b);
    printf("y = %.4f (Контрольное значение ~ 510.1)\n", y);

    // --- Задание 3*: Логические условия ---
    printf("\n--- ЗАДАНИЕ 3*: Проверка логических условий ---\n");
    int A = (int)a;
    int B = (int)b;
    int C = (int)y;

    printf("Целые части: A = %d, B = %d, C = %d\n\n", A, B, C);

    // а) Только одно из чисел A и B четное
    int cond_a = ((A % 2 == 0) && (B % 2 != 0)) || ((A % 2 != 0) && (B % 2 == 0));
    printf("а) Только одно из чисел A и B четное?\n");
    printf("   Ответ: %s (значение: %d)\n", cond_a ? "условие выполнено (1 - да)" : "условие не выполнено (0 - нет)", cond_a);

    // б) Каждое из чисел A, B, C кратно трем
    int cond_b = (A % 3 == 0) && (B % 3 == 0) && (C % 3 == 0);
    printf("б) Каждое из чисел A, B, C кратно трем?\n");
    printf("   Ответ: %s (значение: %d)\n", cond_b ? "условие выполнено (1 - да)" : "условие не выполнено (0 - нет)", cond_b);
}

