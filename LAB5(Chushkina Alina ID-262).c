// Задание 1: Вычисление тригонометрической функции sin(gr)
// -------------------------------------------------------------
void task1(void)
{
    printf("\n--- ЗАДАНИЕ 1 ---\n");
    double gr;

    printf("Введите угол в градусах: ");
    scanf("%lf", &gr);

    // Перевод из градусов в радианы
    double rad = gr * M_PI / 180.0;
    double result = sin(rad);

    printf("Результат: sin(%.2f град) = %.6f\n", gr, result);
}

